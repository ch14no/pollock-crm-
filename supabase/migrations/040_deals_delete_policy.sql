-- ============================================================
-- 040: dealsテーブルにDELETEポリシーが1つも存在しなかった不具合を修正
-- ============================================================
-- 齋藤香奈さんから「商談を削除しても削除されない」と報告（動画で確認：
-- 「削除しました」の成功トーストは出るが、カードが一覧に残り続ける）。
--
-- 調査の結果、001の初期スキーマ以来、dealsテーブルにはSELECT/INSERT/UPDATEの
-- ポリシーのみが存在し、DELETEポリシーが一度も作られていなかったことが判明。
-- RLSが有効なテーブルでDELETEポリシーが無い場合、PostgreSQLはデフォルトで
-- 全ユーザーのDELETEを黙って拒否する（0件削除でエラーにはならない）。
--
-- さらにフロント側の deleteDeal()（lib/db/deals.ts）が削除件数を確認せず
-- error の有無だけを見ていたため、0件削除（＝実質何も起きていない）でも
-- 成功として扱われ、「商談を完全に削除する」ボタンが本番リリース以来一度も
-- 実際には機能していなかった可能性が高い（このプロジェクトで過去に
-- update系で複数回踏んだ「.select()を付けずRLS拒否の0件更新を検出できない」
-- 教訓と同型の不具合）。
--
-- 権限モデルはdeals_update（006）と同じにする: 商談は個人所有物ではなく
-- 事業部で共有するデータのため、同一事業部メンバーなら誰でも削除可
-- （本人限定にしない）＋super_adminは全事業部可。
-- ============================================================

CREATE POLICY "deals_delete" ON public.deals FOR DELETE USING (
  division_id IN (
    SELECT division_id FROM public.user_divisions WHERE user_id = auth.uid()
  )
  OR (SELECT role FROM public.users WHERE id = auth.uid()) = 'super_admin'
);
